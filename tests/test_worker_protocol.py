def assistant(content="", calls=None, usage=None):
    message = {"role": "assistant", "content": content}
    if calls:
        message["tool_calls"] = calls
    result = {"choices": [{"message": message}]}
    if usage is not None:
        result["usage"] = usage
    return result


def tool(name, arguments, identifier="call-1"):
    return {
        "id": identifier, "type": "function",
        "function": {"name": name, "arguments": json.dumps(arguments)},
    }


class FakeProvider:
    name = "mock"
    model = "fake-model"

    def __init__(self, responses, credentials=True):
        self.responses = list(responses)
        self.credentials = credentials

    def has_credentials(self):
        return self.credentials

    def chat(self, messages, tools=None, timeout=120):
        item = self.responses.pop(0)
        if isinstance(item, Exception):
            raise item
        return item


class BlockingLineStream(io.TextIOBase):
    """A line stream the test feeds from another thread.

    ``readline`` blocks until a line is fed or the stream is closed
    (then it returns ``""``, i.e. EOF).
    """

    def __init__(self):
        super().__init__()
        self._lines = collections.deque()
        self._cond = threading.Condition()
        self._closed = False

    def feed(self, line: str) -> None:
        with self._cond:
            self._lines.append(line)
            self._cond.notify_all()

    def close(self) -> None:
        with self._cond:
            self._closed = True
            self._cond.notify_all()
        super().close()

    def readable(self):
        return True

    def readline(self, size=-1):
        with self._cond:
            while not self._lines and not self._closed:
                self._cond.wait()
            if self._lines:
                return self._lines.popleft()
            return ""


class ProtocolTests(unittest.TestCase):
    def test_encode_decode_round_trip(self):
        line = encode_line("pong", 3, id="req-1")
        obj, error = decode_line(line)
        self.assertIsNone(error)
        self.assertEqual(obj["protocol_version"], PROTOCOL_VERSION)
        self.assertEqual(obj["seq"], 3)
        self.assertEqual(obj["type"], "pong")
        self.assertEqual(obj["id"], "req-1")

    def test_decode_blank_line_skipped_silently(self):
        self.assertEqual(decode_line(""), (None, None))
        self.assertEqual(decode_line("   \n"), (None, None))

    def test_decode_malformed_lines(self):
        obj, error = decode_line("not json")
        self.assertIsNone(obj)
        self.assertIn("not valid JSON", error)
        obj, error = decode_line("[1, 2]")
        self.assertIsNone(obj)
        self.assertIn("not a JSON object", error)
        obj, error = decode_line('{"id": "x"}')
        self.assertIsNone(obj)
        self.assertIn("type", error)
        obj, error = decode_line('{"type": 7, "id": "x"}')
        self.assertIsNone(obj)
        self.assertIn("type", error)

    def test_decode_unknown_type_parses(self):
        # Unknown types are not a decode error; the caller ignores them.
        obj, error = decode_line('{"type": "nonsense", "id": "x"}')
        self.assertIsNone(error)
        self.assertEqual(obj["type"], "nonsense")

    def test_new_id_format_and_unique(self):
        ids = {new_id("req") for _ in range(100)}
        self.assertEqual(len(ids), 100)
        self.assertTrue(all(i.startswith("req-") for i in ids))
        self.assertTrue(new_id("appr").startswith("appr-"))

    def test_validate_run_valid(self):
        self.assertIsNone(validate_run_request({"type": "run", "id": "r1", "task": "hi"}))
        self.assertIsNone(
            validate_run_request({"type": "run", "id": "r1", "task": "hi", "fallback": False})
        )
        # Unknown extra keys are allowed (ignored); the protocol grows additively.
        self.assertIsNone(
            validate_run_request({"type": "run", "id": "r1", "task": "hi", "future": 1})
        )

    def test_validate_run_rejects(self):
        self.assertIn("task", validate_run_request({"type": "run", "id": "r1", "task": "  "}))
        self.assertIn("task", validate_run_request({"type": "run", "id": "r1"}))
        self.assertIn("task", validate_run_request({"type": "run", "id": "r1", "task": 7}))
        self.assertIn("fallback", validate_run_request(
            {"type": "run", "id": "r1", "task": "hi", "fallback": True}))
        self.assertIn("fallback", validate_run_request(
            {"type": "run", "id": "r1", "task": "hi", "fallback": "yes"}))
        self.assertIn("provider", validate_run_request(
            {"type": "run", "id": "r1", "task": "hi", "provider": "xai"}))
        self.assertIn("mode", validate_run_request(
            {"type": "run", "id": "r1", "task": "hi", "mode": "full"}))

    def test_validate_decision_valid(self):
        pending = {"id": "req-1", "approval_id": "appr-1"}
        approved, error = validate_approval_decision(
            {"type": "approval_decision", "id": "req-1", "approval_id": "appr-1",
             "decided_by": "human", "approved": True},
            pending,
        )
        self.assertIsNone(error)
        self.assertIs(approved, True)

    def test_validate_decision_rejects(self):
        pending = {"id": "req-1", "approval_id": "appr-1"}
        base = {"type": "approval_decision", "id": "req-1", "approval_id": "appr-1",
                "decided_by": "human", "approved": True}
        self.assertIn("pending", validate_approval_decision(base, None)[1])
        self.assertIn("id", validate_approval_decision({**base, "id": "req-2"}, pending)[1])
        self.assertIn("approval_id", validate_approval_decision(
            {**base, "approval_id": "appr-2"}, pending)[1])
        self.assertIn("human", validate_approval_decision(
            {**base, "decided_by": "host"}, pending)[1])
        self.assertIn("approved", validate_approval_decision(
            {**base, "approved": "yes"}, pending)[1])


class WorkerTestBase(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.workdir = self.root / "work"
        self.workdir.mkdir()
        self.patchers = [
            mock.patch.object(agent_module, "NYRA_HOME", self.root / "angelhome"),
            mock.patch.object(memory_module, "SESSIONS_DIR", self.root / "sessions"),
            mock.patch.object(memory_module, "MEMORY_PATH", self.root / "private-memory"),
        ]
        for patcher in self.patchers:
            patcher.start()

    def tearDown(self):
        for patcher in reversed(self.patchers):
            patcher.stop()
        self.temp.cleanup()

    def _events(self, stdout):
        events = []
        for line in stdout.getvalue().splitlines():
            try:
                events.append(json.loads(line))
            except ValueError:
                pass
        return events

    def _types(self, stdout):
        return [e["type"] for e in self._events(stdout)]

    def _drive(self, lines, responses, mode="auto", approval_timeout=5.0):
        """Feed pre-written stdin lines; return (events, stderr, exit_code)."""
        stdin_text = "".join(
            (json.dumps(line, ensure_ascii=True) if isinstance(line, dict) else line) + "\n"
            for line in lines
        )
        stdin = io.StringIO(stdin_text)
        stdout = io.StringIO()
        stderr = io.StringIO()
        with contextlib.redirect_stderr(stderr):
            emitter = WorkerEmitter(stdout)
            io_obj = WorkerIO(stdin, emitter)
            worker = Worker(agent=None, emitter=emitter, io=io_obj,
                            approval_timeout=approval_timeout)
            agent = Agent(
                provider=FakeProvider(responses), workdir=self.workdir,
                mode=mode, interactive=True, session_id="test-session",
                on_event=worker.on_agent_event, approve_fn=worker.approve_fn,
            )
            worker.agent = agent
            code = worker.serve()
            io_obj.join(timeout=5)
        return self._events(stdout), stderr.getvalue(), code


class WorkerTests(WorkerTestBase):
    def test_golden_transcript_readonly(self):
        events, stderr, code = self._drive(
            [{"type": "run", "id": "req-1", "task": "打个招呼"},
             {"type": "stop", "id": "req-2"}],
            [assistant("你好", usage={"prompt_tokens": 10, "completion_tokens": 5,
                                      "total_tokens": 15})],
        )
        self.assertEqual(code, 0)
        self.assertEqual(
            [e["type"] for e in events],
            ["run_started", "usage", "final", "run_completed"],
        )
        self.assertTrue(all(e["protocol_version"] == PROTOCOL_VERSION for e in events))
        seqs = [e["seq"] for e in events]
        self.assertEqual(seqs, sorted(seqs))
        self.assertEqual(len(set(seqs)), len(seqs))
        started = events[0]
        self.assertEqual(started["id"], "req-1")
        self.assertEqual(started["session_id"], "test-session")
        self.assertEqual(started["provider"], "mock")
        completed = events[-1]
        self.assertEqual(completed["output"], "你好")
        self.assertEqual(completed["usage"]["total_tokens"], 15)
        self.assertEqual(completed["model_switches"], [])

    def test_tool_call_readonly_no_arguments_leaked(self):
        (self.workdir / "note.txt").write_text("hello", encoding="utf-8")
        events, stderr, code = self._drive(
            [{"type": "run", "id": "req-1", "task": "读文件"},
             {"type": "stop", "id": "req-2"}],
            [assistant("", calls=[tool("read_file", {"path": "note.txt"})]),
             assistant("读到了")],
        )
        self.assertEqual(code, 0)
        types = [e["type"] for e in events]
        self.assertEqual(types, ["run_started", "tool_start", "tool_result", "final", "run_completed"])
        start = events[1]
        self.assertEqual(start["name"], "read_file")
        self.assertEqual(start["tool_call_id"], "call-1")
        self.assertNotIn("arguments", start)  # arguments may hold secrets
        result = events[2]
        self.assertTrue(result["ok"])
        self.assertNotIn("result", result)  # raw results may hold secrets

    def test_oversized_output_does_not_deadlock(self):
        big = "x" * 2_000_000
        events, stderr, code = self._drive(
            [{"type": "run", "id": "req-1", "task": "输出很长"},
             {"type": "stop", "id": "req-2"}],
            [assistant(big)],
        )
        self.assertEqual(code, 0)
        completed = events[-1]
        self.assertEqual(completed["type"], "run_completed")
        self.assertEqual(len(completed["output"]), 2_000_000)

    def test_invalid_input_lines_ignored_worker_stays_alive(self):
        events, stderr, code = self._drive(
            ["not json",
             {"type": "nonsense", "id": "x"},
             {"type": "ping", "id": "p1"},
             {"type": "stop", "id": "s1"}],
            [],
        )
        self.assertEqual(code, 0)
        self.assertEqual([e["type"] for e in events], ["pong"])
        self.assertEqual(events[0]["id"], "p1")
        self.assertIn("非法输入", stderr)
        self.assertIn("未知请求类型", stderr)

    def test_unmatched_decision_rejected_and_logged(self):
        events, stderr, code = self._drive(
            [{"type": "approval_decision", "id": "req-9", "approval_id": "appr-9",
              "decided_by": "human", "approved": True},
             {"type": "stop", "id": "s1"}],
            [],
        )
        self.assertEqual(code, 0)
        self.assertEqual(events, [])
        self.assertIn("无待处理审批", stderr)

    def test_run_with_fallback_true_rejected(self):
        events, stderr, code = self._drive(
            [{"type": "run", "id": "req-1", "task": "hi", "fallback": True},
             {"type": "stop", "id": "s1"}],
            [assistant("should not run")],
        )
        self.assertEqual(code, 0)
        self.assertEqual([e["type"] for e in events], ["error"])
        self.assertEqual(events[0]["code"], "invalid_request")
        self.assertIn("fallback", events[0]["message"])

    def test_run_with_provider_override_rejected(self):
        events, stderr, code = self._drive(
            [{"type": "run", "id": "req-1", "task": "hi", "provider": "xai"},
             {"type": "stop", "id": "s1"}],
            [assistant("should not run")],
        )
        self.assertEqual(code, 0)
        self.assertEqual([e["type"] for e in events], ["error"])
        self.assertIn("provider", events[0]["message"])

    def test_empty_stdin_exits_zero(self):
        events, stderr, code = self._drive([], [])
        self.assertEqual(code, 0)
        self.assertEqual(events, [])


class WorkerApprovalTests(WorkerTestBase):
    def _start_interactive(self, responses, mode="auto", approval_timeout=5.0):
        """Start a worker on a feedable stream; return handles for the test."""
        stream = BlockingLineStream()
        stdout = io.StringIO()
        stderr = io.StringIO()
        emitter = WorkerEmitter(stdout)
        io_obj = WorkerIO(stream, emitter)
        worker = Worker(agent=None, emitter=emitter, io=io_obj,
                        approval_timeout=approval_timeout)
        agent = Agent(
            provider=FakeProvider(responses), workdir=self.workdir,
            mode=mode, interactive=True, session_id="test-session",
            on_event=worker.on_agent_event, approve_fn=worker.approve_fn,
        )
        worker.agent = agent
        self._io_obj = io_obj
        self._stream = stream
        self._stdout = stdout
        self._stderr = stderr
        self._worker = worker
        self._stderr_ctx = contextlib.redirect_stderr(stderr)
        self._stderr_ctx.__enter__()
        self._result = {}
        self._thread = threading.Thread(
            target=lambda: self._result.__setitem__("code", worker.serve()),
            daemon=True,
        )
        self._thread.start()
        return worker, stream, stdout, stderr

    def _stop_interactive(self):
        try:
            self._stream.feed(json.dumps({"type": "stop", "id": "req-stop"}) + "\n")
            self._thread.join(timeout=10)
            self.assertFalse(self._thread.is_alive(), "worker thread did not exit")
        finally:
            self._stream.close()
            self._io_obj.join(timeout=5)
            self._stderr_ctx.__exit__(None, None, None)

    def _wait_for(self, event_type, timeout=10.0):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            for event in self._events(self._stdout):
                if event.get("type") == event_type:
                    return event
            time.sleep(0.05)
        self.fail(
            f"no {event_type} event within {timeout}s; got: "
            f"{self._stdout.getvalue()[:800]}"
        )

    def _write_request(self):
        return [
            assistant("", calls=[tool("write_file", {"path": "hello.txt", "content": "hi"})]),
            assistant("写完了"),
        ]

    def test_approval_approved_writes_file(self):
        worker, stream, stdout, stderr = self._start_interactive(self._write_request())
        try:
            stream.feed(json.dumps({"type": "run", "id": "req-1", "task": "写文件"}) + "\n")
            request = self._wait_for("approval_request")
            self.assertEqual(request["tool"], "write_file")
            self.assertTrue(request["approval_id"].startswith("appr-"))
            stream.feed(json.dumps({
                "type": "approval_decision", "id": request["id"],
                "approval_id": request["approval_id"],
                "decided_by": "human", "approved": True,
            }) + "\n")
            completed = self._wait_for("run_completed")
            self.assertEqual(completed["output"], "写完了")
            results = [e for e in self._events(stdout) if e["type"] == "approval_result"]
            self.assertEqual(len(results), 1)
            self.assertIs(results[0]["approved"], True)
            self.assertNotIn("reason", results[0])
            self.assertEqual((self.workdir / "hello.txt").read_text(encoding="utf-8"), "hi")
        finally:
            self._stop_interactive()

    def test_approval_denied_does_not_write(self):
        worker, stream, stdout, stderr = self._start_interactive(self._write_request())
        try:
            stream.feed(json.dumps({"type": "run", "id": "req-1", "task": "写文件"}) + "\n")
            request = self._wait_for("approval_request")
            stream.feed(json.dumps({
                "type": "approval_decision", "id": request["id"],
                "approval_id": request["approval_id"],
                "decided_by": "human", "approved": False,
            }) + "\n")
            completed = self._wait_for("run_completed")
            self.assertEqual(completed["output"], "写完了")
            results = [e for e in self._events(stdout) if e["type"] == "approval_result"]
            self.assertIs(results[0]["approved"], False)
            tool_results = [e for e in self._events(stdout) if e["type"] == "tool_result"]
            self.assertFalse(tool_results[0]["ok"])
            self.assertFalse((self.workdir / "hello.txt").exists())
        finally:
            self._stop_interactive()

    def test_approval_timeout_is_refusal(self):
        worker, stream, stdout, stderr = self._start_interactive(
            self._write_request(), approval_timeout=0.5)
        try:
            stream.feed(json.dumps({"type": "run", "id": "req-1", "task": "写文件"}) + "\n")
            self._wait_for("approval_request")
            # No decision is ever sent: the wait must time out and refuse.
            result = self._wait_for("approval_result", timeout=10.0)
            self.assertIs(result["approved"], False)
            self.assertEqual(result["reason"], "timeout")
            self._wait_for("run_completed")
            self.assertFalse((self.workdir / "hello.txt").exists())
        finally:
            self._stop_interactive()


class WorkerSubprocessTests(unittest.TestCase):
    """Real entry point, real pipes, no model call (ping/stop only)."""

    def test_ping_pong_stop(self):
        root = Path(tempfile.mkdtemp())
        env = dict(os.environ)
        env["HOME"] = str(root)
        repo = Path(__file__).resolve().parent.parent
        proc = subprocess.Popen(
            [sys.executable, "-m", "nyra.worker", "--provider", "ollama"],
            cwd=repo, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            stderr=subprocess.PIPE, text=True, encoding="utf-8", env=env,
        )
        try:
            out, err = proc.communicate(
                '{"type": "ping", "id": "p1"}\n{"type": "stop", "id": "s1"}\n',
                timeout=20,
            )
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.communicate()
            self.fail("worker did not exit on stop")
        self.assertEqual(proc.returncode, 0, f"stderr: {err[-500:]}")
        lines = [json.loads(line) for line in out.splitlines() if line.strip()]
        self.assertEqual([e["type"] for e in lines], ["pong"])
        self.assertEqual(lines[0]["id"], "p1")
        self.assertEqual(lines[0]["protocol_version"], PROTOCOL_VERSION)

    def test_help_exits_zero(self):
        repo = Path(__file__).resolve().parent.parent
        # worker 把 stdout/stderr 显式重配成 UTF-8 再打印中文帮助；父进程
        # 必须按 UTF-8 解码，不能用 Windows 默认的 locale 编码（英文环境
        # 是 cp1252，0x8d 等字节无映射）：communicate() 的读线程会在解码
        # 失败时死掉，result.stdout 变成 None，assertIn 报 TypeError。
        result = subprocess.run(
            [sys.executable, "-m", "nyra.worker", "--help"],
            cwd=repo, capture_output=True, text=True, encoding="utf-8", timeout=20,
            env={**os.environ, "PYTHONIOENCODING": "utf-8"},
        )
        self.assertEqual(result.returncode, 0)
        self.assertIn("nyra.worker", result.stdout)


